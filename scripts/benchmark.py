#!/usr/bin/env python3
"""Record local measurements. The baseline is historical and is never overwritten here."""
import hashlib
import json
import pathlib
import platform
import subprocess

ROOT = pathlib.Path(__file__).resolve().parents[1]
DEST = ROOT / 'docs/benchmarks'


def output(*args):
    return subprocess.check_output(args, cwd=ROOT, text=True)


def main():
    DEST.mkdir(parents=True, exist_ok=True)
    native = output('cargo', 'run', '--release', '--locked', '--quiet', '--example', 'benchmark', '--', '1000')
    json.loads(native)
    (DEST / 'optimized.json').write_text(native)
    rpc = output('go', 'test', '-run', '^$', '-bench', 'BenchmarkRPCDecode', '-benchmem', '-benchtime=100ms', '-count=5', '.')
    (DEST / 'rpc.txt').write_text(rpc)
    codecs = output('cargo', 'run', '--release', '--locked', '--quiet', '--example', 'codecs_benchmark')
    json.loads(codecs)
    (DEST / 'codecs-after.json').write_text(codecs)
    environment = {
        'platform': platform.platform(), 'machine': platform.machine(),
        'rust': output('rustc', '--version').strip(), 'go': output('go', 'version').strip(),
        'native_command': 'cargo run --release --locked --quiet --example benchmark -- 1000',
        'go_command': 'go test -run ^$ -bench BenchmarkRPCDecode -benchmem -benchtime=100ms -count=5 .',
        'method': 'Median of five batch-average per-operation latencies; compilation and fixture reads excluded from timed loops.',
        'scope': 'Native in-memory detection, CRC/AP32 decoding, and Go response decoding; excludes process startup and pipe/file I/O.',
        'codec_command': 'cargo run --release --locked --quiet --example codecs_benchmark',
        'codec_method': 'Median of five batches of 200 operations. codecs-before.json precedes the crc32fast change.',
        'baseline': 'Initial migrated Rust core, before memmem search; baseline.json is a historical measurement, not regenerated by this command.',
        'corpus_sha256': {name: hashlib.sha256((ROOT / 'testdata/upx' / name).read_bytes()).hexdigest() for name in ['pe32.original', 'pe32.packed']},
    }
    (DEST / 'environment.json').write_text(json.dumps(environment, indent=2) + '\n')
    print('Wrote optimized.json, rpc.txt, codecs-after.json and environment.json. Baselines retained.')


if __name__ == '__main__':
    main()
